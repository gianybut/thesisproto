GPX_NS = {'g': 'http://www.topografix.com/GPX/1/1', 'bk': 'urn:bantay-kalsada:capture:1'}
VIDEO_EXT = ('.mov', '.mp4', '.m4v')


def parse_time(s):
    return datetime.fromisoformat(s.replace('Z', '+00:00')) if s else None


def read_gpx(path):
    """(points, capture) where points = [(t_seconds_from_first_point, lat, lon)], and capture is the
    phone app's <bk:capture> attributes (empty dict for a GPX from elsewhere)."""
    root = ET.parse(path).getroot()
    cap = root.find('g:metadata/g:extensions/bk:capture', GPX_NS)
    capture = dict(cap.attrib) if cap is not None else {}
    pts, t0 = [], None
    for p in root.iterfind('.//g:trkpt', GPX_NS):
        t = parse_time(p.findtext('g:time', namespaces=GPX_NS))
        if t is None:
            continue
        t0 = t0 or t
        pts.append(((t - t0).total_seconds(), float(p.get('lat')), float(p.get('lon'))))
    return pts, capture


def position_at(points, video_s, time_offset):
    """(lat, lon) at video second `video_s`, linear between the bracketing GPX points. Same
    convention as backend/services/gps_service.interpolate_gps: GPS time = video time + offset.
    None outside the track (never clamped)."""
    t = video_s + time_offset
    if not points or t < points[0][0] or t > points[-1][0]:
        return None
    lo, hi = 0, len(points) - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if points[mid][0] <= t:
            lo = mid
        else:
            hi = mid
    (ta, la, oa), (tb, lb, ob) = points[lo], points[hi]
    f = 0 if tb == ta else (t - ta) / (tb - ta)
    return la + f * (lb - la), oa + f * (ob - oa)


def haversine_m(lat1, lon1, lat2, lon2):
    r = 6371000.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    a = math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(math.radians(lon2 - lon1) / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def find_recordings():
    """[(folder_name, video_path, gpx_path or None)], sorted by folder name."""
    out = []
    for d in sorted(p for p in VIDEOS.iterdir() if p.is_dir()):
        vids = sorted(p for p in d.iterdir() if p.suffix.lower() in VIDEO_EXT)
        gpxs = sorted(p for p in d.iterdir() if p.suffix.lower() == '.gpx')
        out.append((d.name, vids[0] if vids else None, gpxs[0] if gpxs else None))
    return out


BAND_OVERRIDES = Path(__file__).resolve().parent / 'road_band_overrides.csv'


def band_for(rec):
    """(top, bottom, source) for a recordings.csv row: the team-approved override in
    road_band_overrides.csv (keyed by video file name) when there is one, else the band from the
    GPX as ingest_local.py read it. Use the same values when these recordings go to the server."""
    for o in read_csv(BAND_OVERRIDES):
        if o['video'] == rec['video']:
            return float(o['road_top']), float(o['road_bottom']), 'override'
    return float(rec['road_top']), float(rec['road_bottom']), rec['road_band_source']


def used_recordings():
    """recordings.csv rows still in the dataset (status 'used'; R01-R03 are excluded_handheld)."""
    return [r for r in read_csv(OUT / 'recordings.csv') if (r.get('status') or 'used') == 'used']


def refuse_overwrite(path, what):
    """Stop unless --force: a team-confirmed output must not be regenerated by accident."""
    if path.exists() and '--force' not in sys.argv:
        sys.exit(f'{path.name} exists and holds {what}. Not overwritten; re-run with --force to replace it.')


def read_csv(path):
    with open(path, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def write_csv(path, rows, fields=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = fields or list(rows[0].keys())
    with open(path, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
